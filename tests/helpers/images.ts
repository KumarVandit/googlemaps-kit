/** Simulated protobuf header prefix observed on live vt/proto responses. */
export const PROTO_PREFIX = new Uint8Array([0x0a, 0x80, 0x01, 0x1a, 0x80, 0x01]);

/** Wrap raw image bytes in a protobuf-style envelope like the live tile bodies. */
export function wrapInProtobuf(png: Uint8Array): Uint8Array {
  const wrapped = new Uint8Array(PROTO_PREFIX.length + png.length);
  wrapped.set(PROTO_PREFIX, 0);
  wrapped.set(png, PROTO_PREFIX.length);
  return wrapped;
}
